!> Menus: [[wx_menu_bar]] and [[wx_menu]].
!>
!> ```fortran
!> bar = wx_menu_bar()
!> file = wx_menu()
!> id_open = file%append("&Open..."//achar(9)//"Ctrl+O", help="Open a file")
!> call file%append_separator()
!> id_quit = file%append(id=wxID_EXIT)        ! stock item: standard label
!> call bar%append(file, "&File")
!> call frame%set_menu_bar(bar)
!> call frame%bind(wxEVT_MENU, on_open, id=id_open)
!> ```
!>
!> Menu items are identified by integer ids: stock ids (`wxID_EXIT`,
!> `wxID_ABOUT`, ...) or ids generated by `append`. Selecting an item sends
!> `wxEVT_MENU` to the menu, then to the frame. Bind it on the frame (or the
!> menu), with `id=` for one item.
!>
!> Ownership: a new menu or menu bar is unattached. `bar%append(menu)` and
!> `menu%append_submenu(sub)` transfer the menu, and `frame%set_menu_bar(bar)`
!> transfers the bar to the frame (which destroys any previous one). Unattached
!> menus and bars must be destroyed with `destroy` (or by `app%cleanup()`).
module wx_menus

    use iso_c_binding
    use wx_c_core
    use wx_c_menus
    use wx_base
    use wx_events
    use wx_windows
    implicit none
    private

    public :: wxITEM_NORMAL, wxITEM_CHECK, wxITEM_RADIO
    public :: wxID_OPEN, wxID_CLOSE, wxID_NEW, wxID_SAVE, wxID_SAVEAS, wxID_EXIT
    public :: wxID_UNDO, wxID_REDO, wxID_HELP, wxID_ABOUT, wxID_PREFERENCES
    public :: wxID_CUT, wxID_COPY, wxID_PASTE

    !> A frame's menu bar (a window: `destroy` it only while unattached).
    type, extends(wx_window), public :: wx_menu_bar
    contains
        procedure :: append => wx_menu_bar_append
        procedure :: menu_count => wx_menu_bar_menu_count
    end type wx_menu_bar

    !> Create an (unattached) menu bar.
    interface wx_menu_bar
        module procedure wx_menu_bar_new
    end interface wx_menu_bar

    !> A menu of items (in a menu bar, or a submenu).
    type, extends(wx_evt_handler), public :: wx_menu
    contains
        procedure :: append => wx_menu_append
        procedure :: append_separator => wx_menu_append_separator
        procedure :: append_submenu => wx_menu_append_submenu
        procedure :: item_count => wx_menu_item_count
        procedure :: enable => wx_menu_enable
        procedure :: is_enabled => wx_menu_is_enabled
        procedure :: check => wx_menu_check
        procedure :: is_checked => wx_menu_is_checked
        procedure :: set_label => wx_menu_set_label
        procedure :: get_label => wx_menu_get_label
        procedure :: emit_select => wx_menu_emit_select
        procedure :: destroy => wx_menu_destroy
    end type wx_menu

    !> Create an (unattached) menu.
    interface wx_menu
        module procedure wx_menu_new
    end interface wx_menu

contains

    ! -------------------------------------------------------------------------
    ! wx_menu_bar

    !> Create an unattached menu bar (give it to a frame with `set_menu_bar`).
    type(wx_menu_bar) function wx_menu_bar_new(stat)
        integer, intent(out), optional :: stat
        integer(c_int) :: status
        status = wxf_menu_bar_create(wx_menu_bar_new%h)
        if (status /= WX_OK) wx_menu_bar_new%h = 0
        call wx_check(status, stat)
    end function wx_menu_bar_new

    !> Append `menu` with `title` (e.g. "&File"); the menu bar then owns it.
    subroutine wx_menu_bar_append(self, menu, title, stat)
        class(wx_menu_bar), intent(inout) :: self
        class(wx_menu), intent(in) :: menu
        character(len=*), intent(in) :: title
        integer, intent(out), optional :: stat
        call wx_check(wxf_menu_bar_append(self%h, menu%h, title, len(title, c_int)), stat)
    end subroutine wx_menu_bar_append

    !> Number of menus.
    integer function wx_menu_bar_menu_count(self, stat)
        class(wx_menu_bar), intent(in) :: self
        integer, intent(out), optional :: stat
        integer(c_int) :: n
        n = 0
        call wx_check(wxf_menu_bar_menu_count(self%h, n), stat)
        wx_menu_bar_menu_count = n
    end function wx_menu_bar_menu_count

    ! -------------------------------------------------------------------------
    ! wx_menu

    !> Create an unattached menu (`title` is shown only for popup menus).
    type(wx_menu) function wx_menu_new(title, stat)
        character(len=*), intent(in), optional :: title
        integer, intent(out), optional :: stat
        integer(c_int) :: status
        if (present(title)) then
            status = wxf_menu_create(title, len(title, c_int), wx_menu_new%h)
        else
            status = wxf_menu_create('', 0_c_int, wx_menu_new%h)
        end if
        if (status /= WX_OK) wx_menu_new%h = 0
        call wx_check(status, stat)
    end function wx_menu_new

    !> Append an item and return its id. `text` may contain a mnemonic (`&`)
    !> and an accelerator after a tab character (`"&Open..."//achar(9)//"Ctrl+O"`).
    !> `help` is shown in the
    !> frame's status bar while the item is highlighted. `id`: a stock id
    !> (then `text` may be omitted) or a new id is generated. `kind`:
    !> `wxITEM_NORMAL` (default), `wxITEM_CHECK` or `wxITEM_RADIO`.
    integer function wx_menu_append(self, text, help, id, kind, stat)
        class(wx_menu), intent(inout) :: self
        character(len=*), intent(in), optional :: text, help
        integer, intent(in), optional :: id, kind
        integer, intent(out), optional :: stat
        integer(c_int) :: i, k, out
        character(len=:), allocatable :: t, hp
        i = wxID_ANY
        if (present(id)) i = int(id, c_int)
        k = wxITEM_NORMAL
        if (present(kind)) k = int(kind, c_int)
        t = ''
        if (present(text)) t = text
        hp = ''
        if (present(help)) hp = help
        out = 0
        call wx_check(wxf_menu_append(self%h, i, t, len(t, c_int), hp, len(hp, c_int), k, out), stat)
        wx_menu_append = out
    end function wx_menu_append

    !> Append a separator line.
    subroutine wx_menu_append_separator(self, stat)
        class(wx_menu), intent(inout) :: self
        integer, intent(out), optional :: stat
        call wx_check(wxf_menu_append_separator(self%h), stat)
    end subroutine wx_menu_append_separator

    !> Append `submenu` (which this menu then owns) as an item labelled `text`.
    subroutine wx_menu_append_submenu(self, submenu, text, stat)
        class(wx_menu), intent(inout) :: self
        class(wx_menu), intent(in) :: submenu
        character(len=*), intent(in) :: text
        integer, intent(out), optional :: stat
        call wx_check(wxf_menu_append_submenu(self%h, submenu%h, text, len(text, c_int)), stat)
    end subroutine wx_menu_append_submenu

    !> Number of items (including separators and submenus).
    integer function wx_menu_item_count(self, stat)
        class(wx_menu), intent(in) :: self
        integer, intent(out), optional :: stat
        integer(c_int) :: n
        n = 0
        call wx_check(wxf_menu_item_count(self%h, n), stat)
        wx_menu_item_count = n
    end function wx_menu_item_count

    !> Enable (or with `enable=.false.` disable) item `id` (also in submenus).
    subroutine wx_menu_enable(self, id, enable, stat)
        class(wx_menu), intent(inout) :: self
        integer, intent(in) :: id
        logical, intent(in), optional :: enable
        integer, intent(out), optional :: stat
        logical :: e
        e = .true.
        if (present(enable)) e = enable
        call wx_check(wxf_menu_enable(self%h, int(id, c_int), wx_int(e)), stat)
    end subroutine wx_menu_enable

    !> True if item `id` is enabled.
    logical function wx_menu_is_enabled(self, id, stat)
        class(wx_menu), intent(in) :: self
        integer, intent(in) :: id
        integer, intent(out), optional :: stat
        integer(c_int) :: v
        v = 0
        call wx_check(wxf_menu_is_enabled(self%h, int(id, c_int), v), stat)
        wx_menu_is_enabled = wx_logical(v)
    end function wx_menu_is_enabled

    !> Check (or with `check=.false.` uncheck) check or radio item `id`,
    !> without sending an event.
    subroutine wx_menu_check(self, id, check, stat)
        class(wx_menu), intent(inout) :: self
        integer, intent(in) :: id
        logical, intent(in), optional :: check
        integer, intent(out), optional :: stat
        logical :: c
        c = .true.
        if (present(check)) c = check
        call wx_check(wxf_menu_check(self%h, int(id, c_int), wx_int(c)), stat)
    end subroutine wx_menu_check

    !> True if check or radio item `id` is checked.
    logical function wx_menu_is_checked(self, id, stat)
        class(wx_menu), intent(in) :: self
        integer, intent(in) :: id
        integer, intent(out), optional :: stat
        integer(c_int) :: v
        v = 0
        call wx_check(wxf_menu_is_checked(self%h, int(id, c_int), v), stat)
        wx_menu_is_checked = wx_logical(v)
    end function wx_menu_is_checked

    !> Set the label of item `id` (mnemonic and accelerator as for `append`).
    subroutine wx_menu_set_label(self, id, label, stat)
        class(wx_menu), intent(inout) :: self
        integer, intent(in) :: id
        character(len=*), intent(in) :: label
        integer, intent(out), optional :: stat
        call wx_check(wxf_menu_set_label(self%h, int(id, c_int), label, len(label, c_int)), stat)
    end subroutine wx_menu_set_label

    !> The label of item `id`, without mnemonic or accelerator.
    function wx_menu_get_label(self, id, stat) result(s)
        class(wx_menu), intent(in) :: self
        integer, intent(in) :: id
        integer, intent(out), optional :: stat
        character(len=:), allocatable :: s
        type(c_ptr) :: p
        integer(c_int) :: len, status
        status = wxf_menu_get_label(self%h, int(id, c_int), p, len)
        s = wx_take_string(status, p, len, stat)
    end function wx_menu_get_label

    !> Select item `id` as the user would (for tests and automation): toggle
    !> a check item or check a radio item, then send `wxEVT_MENU` to the menu
    !> and its frame. Handlers run before this returns. Fails with
    !> `WX_ERR_STATE` for a disabled item.
    subroutine wx_menu_emit_select(self, id, stat)
        class(wx_menu), intent(inout) :: self
        integer, intent(in) :: id
        integer, intent(out), optional :: stat
        call wx_check(wxf_menu_emit_select(self%h, int(id, c_int)), stat)
    end subroutine wx_menu_emit_select

    !> Destroy an unattached menu (attached ones are destroyed by their owner).
    subroutine wx_menu_destroy(self, stat)
        class(wx_menu), intent(inout) :: self
        integer, intent(out), optional :: stat
        call wx_check(wxf_menu_destroy(self%h), stat)
    end subroutine wx_menu_destroy

end module wx_menus
